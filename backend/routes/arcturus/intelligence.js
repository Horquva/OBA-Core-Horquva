/**
 * GET /api/arcturus/intelligence/:experiment_id
 * Fetch structured assessment for an experiment.
 * Only available if experiment has been validated.
 */
router.get('/:experiment_id', (req, res) => {
  const { experiment_id } = req.params;

  // Check if assessment exists
  if (mockAssessments[experiment_id]) {
    return res.json(mockAssessments[experiment_id]);
  }

  // Assessment not yet available (either not validated or no assessment generated)
  return res.status(404).json({
    error: 'Structured assessment not yet available',
    experiment_id,
    message: 'This experiment must be validated before an assessment can be generated.',
  });
});

module.exports = router;
