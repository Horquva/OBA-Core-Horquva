# ============================================================
# A. FULL PIPELINE INTEGRATION TEST
# ============================================================

def test_full_pipeline_end_to_end(client):
    """
    Walks the entire roadmap lifecycle in one test, using two
    realistic organizational signals worded to trigger the same
    dimensions:

        Signal -> Impact -> Pattern -> Future Model
        -> Candidate Capability -> Intelligence Trace

    This is the test that actually proves Day 4 through Day 7 connect
    to each other correctly, not just that each one works alone.
    """
    description = (
        "Company X flattened its management structure, removing a layer "
        "of middle management and giving teams direct decision-making "
        "authority over their own hiring and daily operations."
    )

    # Step 1: ingest two similarly-worded real-world-style signals
    tag_a, tag_b = uuid.uuid4().hex[:6], uuid.uuid4().hex[:6]
    signal_a = client.post(
        "/signals?check_duplicates=false",
        json={"title": f"Flattened structure {tag_a}", "description": description, "source": "integration-test"},
    ).json()
    signal_b = client.post(
        "/signals?check_duplicates=false",
        json={"title": f"Flattened structure {tag_b}", "description": description, "source": "integration-test"},
    ).json()
    assert signal_a["id"] != signal_b["id"]

    # Step 2: evidence can be attached to a real signal
    evidence = client.post(
        "/evidence",
        json={
            "signal_id": signal_a["id"],
            "description": "Org chart diff showing removed management layer.",
            "source_reference": "internal report",
        },
    )
    assert evidence.status_code == 200

    # Step 3: impact analysis (Day 4)
    impacts_a = client.post(f"/signals/{signal_a['id']}/analyze").json()
    impacts_b = client.post(f"/signals/{signal_b['id']}/analyze").json()
    assert len(impacts_a) > 0
    assert len(impacts_b) > 0
    assert {i["dimension_id"] for i in impacts_a} == {i["dimension_id"] for i in impacts_b}

    # Step 4: pattern detection (Day 5)
    client.post("/patterns/detect")
    rels_a = client.get(f"/relationships?source_id={signal_a['id']}").json()
    pattern_id = next(r["target_id"] for r in rels_a if r["target_type"] == "pattern")
    pattern = client.get(f"/patterns").json()
    assert any(p["id"] == pattern_id for p in pattern)

    # Step 5: future model built from the pattern (Day 6)
    model = client.post("/models/build", json={"pattern_ids": [pattern_id]}).json()
    assert model["confidence"] == "hypothesized"
    support = client.get(f"/models/{model['id']}/support").json()
    assert any(s["source_id"] == pattern_id for s in support)

    # Step 6: candidate capability suggested from the model (Day 7)
    capability = client.post("/capabilities/build", json={"model_id": model["id"]}).json()
    assert capability["status"] == "candidate"  # never auto-approved

    # Step 7: the full trail is retrievable from a single signal
    trace = client.get(f"/intelligence/trace/{signal_a['id']}").json()
    assert trace["signal"]["id"] == signal_a["id"]
    assert len(trace["impacts"]) > 0
    assert any(p["id"] == pattern_id for p in trace["patterns"])
    assert any(m["id"] == model["id"] for m in trace["models"])
    assert any(c["id"] == capability["id"] for c in trace["candidate_capabilities"])

    # Step 8: evidence state discipline held throughout the whole run -
    # nothing generated by the engines claims to be more certain than
    # it actually is
    assert all(i["confidence"] == "inferred" for i in impacts_a)
    assert pattern_id in [p["id"] for p in pattern]
    assert model["confidence"] == "hypothesized"


