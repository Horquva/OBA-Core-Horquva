def test_malformed_signal_missing_required_field_returns_422(client):
    response = client.post("/signals?check_duplicates=false", json={"description": "no title given"})
    assert response.status_code == 422


def test_evidence_for_nonexistent_signal_returns_404_or_error(client):
    response = client.post(
        "/evidence",
        json={"signal_id": "does-not-exist", "description": "y", "source_reference": "x"},
    )
    assert response.status_code in (404, 400)


def test_analyze_nonexistent_signal_returns_404(client):
    assert client.post("/signals/does-not-exist/analyze").status_code == 404


def test_analyze_signal_with_no_matching_keywords_still_returns_200(client):
    """A signal that matches NO dimension keywords is still valid input -
    the engine should return an empty impact list, not error out."""
    signal = client.post(
        "/signals?check_duplicates=false",
        json={"title": "Weather note", "description": "It rained yesterday.", "source": "t"},
    ).json()
    response = client.post(f"/signals/{signal['id']}/analyze")
    assert response.status_code == 200
    assert response.json() == []


def test_detect_patterns_with_no_signals_returns_empty_list(client):
    """Running pattern detection on a database with zero analyzed
    signals should return an empty list, not crash."""
    response = client.post("/patterns/detect")
    assert response.status_code == 200
    assert isinstance(response.json(), list)


def test_build_model_with_empty_pattern_list_returns_404(client):
    response = client.post("/models/build", json={"pattern_ids": []})
    assert response.status_code == 404


def test_build_capability_missing_model_returns_404(client):
    response = client.post("/capabilities/build", json={"model_id": "fake"})
    assert response.status_code == 404


def test_trace_missing_signal_returns_404(client):
    response = client.get("/intelligence/trace/does-not-exist")
    assert response.status_code == 404


def test_duplicate_signal_still_blocked_by_default(client):
    """Confirms Day 2's duplicate detection is still active and wasn't
    accidentally weakened by anything added in Days 4-7."""
    payload = {
        "title": "Duplicate check integration test",
        "description": "This exact wording should be flagged as a duplicate on the second attempt.",
        "source": "integration-test",
    }
    first = client.post("/signals", json=payload)
    assert first.status_code == 200
    second = client.post("/signals", json=payload)
    assert second.status_code == 409


def test_force_reanalysis_does_not_corrupt_relationship_count(client):
    """Re-running impact analysis with force=true should add impacts
    and relationships, never remove or corrupt existing ones."""
    signal = client.post(
        "/signals?check_duplicates=false",
        json={"title": "Reanalysis test", "description": "New governance policy changed board approval.", "source": "t"},
    ).json()
    client.post(f"/signals/{signal['id']}/analyze")
    before = len(client.get(f"/relationships?source_id={signal['id']}").json())

    client.post(f"/signals/{signal['id']}/analyze?force=true")
    after = len(client.get(f"/relationships?source_id={signal['id']}").json())

    assert after > before
